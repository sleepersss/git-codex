"""One bundle, two entries: GUI without console and hidden worker with stdout."""
from pathlib import Path
import subprocess,sys,json
from app_paths import APP_VERSION
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]
out=ROOT/('outputs/mod-extractor-desktop-v'+APP_VERSION);build=ROOT/('work/mod-extractor-build-v'+APP_VERSION);build.mkdir(parents=True,exist_ok=True)
datas=[(str(p),'tools/mod-extractor') for p in HERE.glob('*.py') if not p.name.startswith('test_')]
datas.extend([(str(HERE/'config.json'),'tools/mod-extractor'),(str(ROOT/'model-library/library.py'),'model-library'),
              (str(ROOT/'model-library/inspect_blend.py'),'model-library'),(str(ROOT/'model-library/locking.py'),'model-library')])
spec=build/'ModExtractor.spec'
spec.write_text(f'''# Generated by build_desktop.py
from pathlib import Path
a=Analysis([{str(HERE/'desktop.py')!r}],pathex=[{str(HERE)!r},{str(ROOT/'model-library')!r}],
    binaries=[],datas={datas!r},hiddenimports=['sqlite3','library','locking'],hookspath=[],runtime_hooks=[],excludes=['tkinter','PyQt5','PyQt6','matplotlib','scipy','numpy'],noarchive=False)
# Qt uses Windows system ICU. Poppler on PATH supplies an incompatible ICU.
# Exclude its transitive ICU binaries; never redistribute Windows system DLLs.
a.binaries=[entry for entry in a.binaries if not Path(entry[0]).name.lower().startswith('icu')]
pyz=PYZ(a.pure)
gui=EXE(pyz,a.scripts,[],exclude_binaries=True,name='ModExtractor',console=False,debug=False)
worker=EXE(pyz,a.scripts,[],exclude_binaries=True,name='ModExtractorWorker',console=True,debug=False)
bundle=COLLECT(gui,worker,a.binaries,a.datas,strip=False,upx=False,name='ModExtractor')
''',encoding='utf-8')
subprocess.run([sys.executable,'-m','PyInstaller','--clean','--noconfirm','--distpath',str(out),'--workpath',str(build/'cache'),str(spec)],check=True)
from app_paths import resolve_paths
previous=ROOT/'outputs/mod-extractor-desktop-v3.3-r6/ModExtractor/settings.json'
if not previous.is_file():previous=out/'ModExtractor/settings.json'
cfg=json.loads(previous.read_text(encoding='utf-8-sig')) if previous.is_file() else resolve_paths()
cfg.pop('config_path',None)
(out/'ModExtractor/settings.json').write_text(json.dumps(cfg,ensure_ascii=False,indent=2),encoding='utf-8')
import hashlib
from datetime import datetime,timezone
manifest={'version':APP_VERSION,'built_at':datetime.now(timezone.utc).isoformat(),
    'source_files':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in HERE.glob('*.py') if not p.name.startswith('test_')},
    'library_source_files':{name:hashlib.sha256((ROOT/'model-library'/name).read_bytes()).hexdigest() for name in ('library.py','locking.py','inspect_blend.py')},
    'previous_bundle_preserved':str(previous.parent),'settings_copied_from':str(previous) if previous.is_file() else None}
(out/'ModExtractor/release.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
print(str(out/'ModExtractor/ModExtractor.exe'))
